import { readFileSync } from 'node:fs';
import { strict as assert } from 'node:assert';
import { pathToFileURL } from 'node:url';
const [sourcePath = new URL('../scripts/server-v3.js', import.meta.url), helperPath = new URL('../scripts/oneuse-cleanup.js', import.meta.url)] = process.argv.slice(2);
const source = readFileSync(sourcePath, 'utf8');
const helpers = await import(helperPath instanceof URL ? helperPath : pathToFileURL(helperPath));
const body = source.match(/\n  reap\(\) \{([\s\S]*?)\n  \},\n  oneshotWaiters:/)?.[1];
assert.ok(body, 'extract actual production manager.reap body');
const key='router-oneuse-regression', regular='regular-chat';
const pending=new Map([['tool',{chatKey:key}],['regular-tool',{chatKey:regular}]]);
let events=[];
const old=Date.now()-2*3600e3;
const make=(key,busy=false)=>({key,busy,live:true,lastUsed:old,park(why){events.push(`${key}:${why}`)}});
const c=make(key), r=make(regular), busy=make('busy',true), orphan=make('orphan');
const m={oneuse:new Map([[key,c],['busy',busy],['orphan',orphan]]),chats:new Map([[regular,r]]),destroyOneUse(k){events.push(k);this.oneuse.delete(k)}};
const reap=new Function('pendingToolUses','ONEUSE_IDLE_MS','IDLE_TTL_MS','isIdleCleanupEligible','isLiveEvictionCandidate',`return function(){${body}}`)(pending,900e3,3600e3,helpers.isIdleCleanupEligible,helpers.isLiveEvictionCandidate);
reap.call(m);
assert.ok(!events.includes(key), 'oneuse waiting on own tool must survive >15min');
assert.ok(!events.includes(`${regular}:idle`),'regular waiting on own tool must survive idle TTL');
assert.ok(!events.includes('busy'),'busy session protected');
assert.ok(events.includes('orphan'),'unrelated pending tool must not disable orphan cleanup');
pending.clear();events=[];reap.call(m);
assert.ok(events.includes(key),'oneuse cleaned after pending tool removed');
assert.ok(events.includes(`${regular}:idle`),'regular parked after pending tool removed');
console.log('actual production reap: pending oneuse/regular protected, busy protected, orphan reaped, later cleanup PASS');
